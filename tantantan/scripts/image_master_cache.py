#!/usr/bin/env python3
"""Private generated-master cache. Never uploads sources or modifies publication.

Remote providers implement probe/put/get via a trusted, locally configured command.
The directory provider is deliberately non-durable and is for contract tests only.
"""
import argparse
import copy
import hashlib
import io
import json
import os
from pathlib import Path
import re
import subprocess
import tempfile
from datetime import datetime, timezone
import warnings

from PIL import Image

VERSION = 'private-master-cache-v1'
HASH = re.compile(r'^[a-f0-9]{64}$')
BACKEND_ID = re.compile(r'^[a-z][a-z0-9-]{0,39}$')
MAX_BYTES = 64 * 1024 * 1024
MAX_PIXELS = 50_000_000
OPERATIONS = {'style-transfer-and-cleanup', 'illustration-edit', 'illustration-generation'}


class CacheError(Exception):
    """Only fixed, non-sensitive error codes may cross the CLI boundary."""


def require(condition, code):
    if not condition:
        raise CacheError(code)


def digest(data):
    return hashlib.sha256(data).hexdigest()


def read_bytes(path):
    path = Path(path)
    require(not path.is_symlink(), 'symlink-forbidden')
    with path.open('rb') as stream:
        data = stream.read(MAX_BYTES + 1)
    require(0 < len(data) <= MAX_BYTES, 'file-size-limit')
    return data


def inspect_png(data):
    require(data.startswith(b'\x89PNG\r\n\x1a\n'), 'generated-png-required')
    try:
        with warnings.catch_warnings():
            warnings.simplefilter('error', Image.DecompressionBombWarning)
            with Image.open(io.BytesIO(data)) as im:
                require(im.format == 'PNG' and not getattr(im, 'is_animated', False), 'single-png-required')
                require(im.width * im.height <= MAX_PIXELS, 'pixel-limit')
                require(im.mode in {'RGB', 'RGBA'}, 'rgb-png-required')
                # Reject EXIF, textual chunks (including XMP), and unknown metadata.
                require(not (set(im.info) - {'gamma', 'srgb', 'transparency'}), 'metadata-forbidden')
                im.verify()
            with Image.open(io.BytesIO(data)) as im:
                im.load()
                require(not (set(im.info) - {'gamma', 'srgb', 'transparency'}), 'metadata-forbidden')
                return {'sha256': digest(data), 'bytes': len(data),
                        'width': im.width, 'height': im.height, 'format': 'PNG'}
    except CacheError:
        raise
    except Exception:
        raise CacheError('decode-failed') from None


def revision(lineage, revision_id):
    matches = [(image, r) for image in lineage['images'] for r in image['revisions']
               if r['revisionId'] == revision_id]
    require(len(matches) == 1, 'revision-not-unique')
    return matches[0]


def eligible(image, r):
    require(r.get('status') != 'legacy-verified', 'legacy-history-unknown')
    require(r.get('status') in {'validated', 'approved'} and bool(r.get('validation')), 'revision-not-validated')
    require(r.get('lifecycle') in {'active', 'archived'}, 'revision-not-reusable')
    require(r.get('operation') in OPERATIONS, 'generated-illustration-required')
    require(image.get('sourceArtifactRef') is None, 'original-upload-forbidden')
    require(bool(HASH.fullmatch(r.get('sourceId') or '')) and
            bool(HASH.fullmatch(r.get('outputSha256') or '')) and
            bool(HASH.fullmatch(r.get('recipeKey') or '')), 'provenance-incomplete')
    recipe = r.get('recipe')
    require(isinstance(recipe, dict) and recipe.get('sourceSha256') == r['sourceId'] and
            recipe.get('cacheVersion') == 'travel-photo-cache-v1', 'recipe-incomplete')
    canonical = json.dumps(recipe, ensure_ascii=False, sort_keys=True, separators=(',', ':'), allow_nan=False).encode()
    require(digest(canonical) == r['recipeKey'], 'recipe-key-mismatch')


def verify_master(lineage, image, r, data, record=None):
    eligible(image, r)
    meta = inspect_png(data)
    require(meta['sha256'] == r['outputSha256'], 'master-hash-mismatch')
    original_hashes = {i.get('sourceSha256') for i in lineage['images']}
    original_hashes.update(rev.get('sourceId') for i in lineage['images'] for rev in i['revisions'])
    published_hashes = {v.get('sha256') for i in lineage['images'] for rev in i['revisions'] for v in rev.get('variants', [])}
    require(meta['sha256'] not in original_hashes, 'original-upload-forbidden')
    require(meta['sha256'] not in published_hashes, 'published-variant-is-not-master')
    dimensions = r.get('optimizationRecipe', {}).get('generatedDimensions')
    if dimensions is not None:
        require(dimensions == [meta['width'], meta['height']], 'master-dimensions-mismatch')
    if record is not None:
        require(all(record.get(key) == value for key, value in meta.items()), 'receipt-metadata-mismatch')
    return meta


def private_path(path, repo):
    """Keep generated bytes outside the entire checkout, including Vite's public/."""
    path = Path(path).absolute()
    for part in [path, *path.parents]:
        require(not part.is_symlink(), 'symlink-forbidden')
    require(not path.resolve().is_relative_to(Path(repo).resolve()), 'private-path-inside-repository')
    return path


def atomic_file(path, data, *, replace=False):
    """Publish complete bytes; exclusive hard link avoids clobber on concurrent creates."""
    path = Path(path)
    fd, temp = tempfile.mkstemp(prefix='.master-', dir=path.parent)
    try:
        with os.fdopen(fd, 'wb') as stream:
            stream.write(data)
            stream.flush()
            os.fsync(stream.fileno())
        if replace:
            os.replace(temp, path)
        else:
            os.link(temp, path)
        directory_fd = os.open(path.parent, os.O_RDONLY)
        try:
            os.fsync(directory_fd)
        finally:
            os.close(directory_fd)
    finally:
        if os.path.exists(temp):
            os.unlink(temp)


class DirectoryBackend:
    """Private filesystem CAS reference implementation; NEVER claims durability."""
    def __init__(self, root, repo, backend_id='local-test'):
        require(bool(BACKEND_ID.fullmatch(backend_id)), 'invalid-backend-id')
        self.backend_id = backend_id
        self.root = private_path(root, repo)
        self.root.mkdir(mode=0o700, parents=True, exist_ok=True)
        require(self.root.stat().st_mode & 0o077 == 0, 'private-directory-required')

    def probe(self):
        return {'backendId': self.backend_id, 'private': True, 'durable': False,
                'read': True, 'write': True, 'immutable': True, 'retention': 'local-test-only'}

    def object_path(self, key):
        require(bool(HASH.fullmatch(key)), 'invalid-object-key')
        path = self.root / key
        require(not path.is_symlink(), 'symlink-forbidden')
        return path

    def put(self, key, data):
        require(digest(data) == key, 'object-key-mismatch')
        path = self.object_path(key)
        try:
            atomic_file(path, data)
        except FileExistsError:
            pass
        require(read_bytes(path) == data, 'immutable-object-conflict')

    def get(self, key):
        return read_bytes(self.object_path(key))


class CommandBackend:
    """JSON stdin/stdout contract; shell is never used, credentials stay in provider."""
    def __init__(self, command, backend_id):
        require(isinstance(command, list) and bool(command) and
                all(isinstance(x, str) and x for x in command), 'invalid-provider-command')
        require(bool(BACKEND_ID.fullmatch(backend_id)), 'invalid-backend-id')
        self.command, self.backend_id = command, backend_id

    def call(self, operation, **kwargs):
        request = {'protocol': VERSION, 'operation': operation, **kwargs}
        try:
            result = subprocess.run(self.command, input=json.dumps(request).encode(),
                                    capture_output=True, timeout=60, check=True)
            require(len(result.stdout) <= 16_384, 'provider-response-limit')
            response = json.loads(result.stdout)
            require(isinstance(response, dict) and response.get('ok') is True, 'provider-failed')
            return response
        except CacheError:
            raise
        except Exception:
            # Provider diagnostics may contain credentials or signed URLs.
            raise CacheError('provider-unavailable') from None

    def probe(self):
        return self.call('probe')

    def put(self, key, data):
        with tempfile.TemporaryDirectory(prefix='master-upload-') as directory:
            path = Path(directory) / 'generated.png'
            atomic_file(path, data)
            self.call('put', key=key, path=str(path), bytes=len(data), sha256=key)

    def get(self, key):
        with tempfile.TemporaryDirectory(prefix='master-download-') as directory:
            path = Path(directory) / 'generated.png'
            self.call('get', key=key, path=str(path), maxBytes=MAX_BYTES)
            return read_bytes(path)


def capabilities(backend, *, write=False):
    info = backend.probe()
    require(info.get('backendId') == backend.backend_id, 'backend-id-mismatch')
    require(info.get('private') is True and info.get('read') is True and
            info.get('immutable') is True, 'private-backend-not-ready')
    if write:
        require(info.get('write') is True, 'backend-not-writable')
    if info.get('durable') is True:
        require(info.get('retention') == 'until-explicit-delete', 'retention-not-confirmed')
    return info


def persist(lineage, revision_id, data, attestation, backend):
    image, r = revision(lineage, revision_id)
    meta = verify_master(lineage, image, r, data)
    # This is an operator provenance assertion, not an automated visual classifier.
    require(attestation == {'kind': 'generated-illustration', 'revisionId': revision_id,
                            'outputSha256': meta['sha256'], 'sourceCopiesExcluded': True,
                            'visualReviewPassed': True}, 'generated-provenance-attestation-required')
    info = capabilities(backend, write=True)
    require(info.get('durable') is True or isinstance(backend, DirectoryBackend), 'durability-not-confirmed')
    backend.put(meta['sha256'], data)  # immutable/idempotent; no blind retry on ambiguity
    restored = backend.get(meta['sha256'])
    verify_master(lineage, image, r, restored, meta)
    require(restored == data, 'readback-mismatch')
    if info.get('durable') is not True:
        return None, {'state': 'local-verified-not-persisted', 'reusable': False}
    # Probe again: a changed ACL or credential state must not create a ready receipt.
    require(capabilities(backend).get('durable') is True, 'durability-not-confirmed')
    record = {'schemaVersion': 1, 'backendId': backend.backend_id, **meta,
              'verifiedAt': datetime.now(timezone.utc).isoformat(),
              'verification': 'download-sha256-decode', 'retention': 'until-explicit-delete'}
    updated = copy.deepcopy(lineage)
    _, target = revision(updated, revision_id)
    target['artifactRef'] = f"private-master-v1:{backend.backend_id}:{meta['sha256']}"
    target['masterAvailability'] = 'private-verified'
    target['masterCache'] = record
    return updated, {'state': 'private-verified', 'reusable': True, 'revisionId': revision_id}


def retrieve(lineage, revision_id, backend):
    image, r = revision(lineage, revision_id)
    eligible(image, r)
    record = r.get('masterCache')
    require(bool(record) and r.get('masterAvailability') == 'private-verified', 'master-unpersisted')
    require(record.get('schemaVersion') == 1 and record.get('verification') == 'download-sha256-decode'
            and record.get('retention') == 'until-explicit-delete', 'invalid-master-receipt')
    require(backend is not None, 'backend-unconfigured')
    require(record.get('backendId') == backend.backend_id, 'wrong-backend')
    require(r.get('artifactRef') == f"private-master-v1:{backend.backend_id}:{r['outputSha256']}", 'reference-mismatch')
    require(capabilities(backend).get('durable') is True, 'durability-not-confirmed')
    data = backend.get(r['outputSha256'])
    verify_master(lineage, image, r, data, record)
    return data


def failure(error):
    if isinstance(error, CacheError):
        return str(error)
    if isinstance(error, FileNotFoundError):
        return 'master-missing'
    if isinstance(error, PermissionError):
        return 'access-denied'
    return 'cache-unavailable'


def miss(code):
    return {'state': code, 'reusable': False, 'action': 'keep-published-webp'}


def restore(lineage, revision_id, backend, destination, repo):
    try:
        destination = private_path(destination, repo)
        require(destination.parent.is_dir(), 'destination-directory-missing')
        data = retrieve(lineage, revision_id, backend)
        if destination.exists():
            require(read_bytes(destination) == data, 'destination-conflict')
        else:
            atomic_file(destination, data)
        return {'state': 'restored-verified', 'reusable': True, 'revisionId': revision_id}
    except Exception as error:
        return miss(failure(error))


def lookup(lineage, recipe_key, backend, selected_revision=None):
    require(bool(HASH.fullmatch(recipe_key)), 'invalid-recipe-key')
    candidates, unavailable = [], []
    for image in lineage['images']:
        for r in image['revisions']:
            if r.get('recipeKey') != recipe_key or (selected_revision and r['revisionId'] != selected_revision):
                continue
            try:
                retrieve(lineage, r['revisionId'], backend)
                candidates.append(r['revisionId'])
            except Exception as error:
                unavailable.append({'revisionId': r['revisionId'], 'reason': failure(error)})
    if len(candidates) == 1:
        return {'state': 'verified-hit', 'reusable': True, 'revisionId': candidates[0]}
    return {**miss('ambiguous-candidates' if candidates else 'cache-miss'),
            'candidates': candidates, 'unavailable': unavailable}


def commit_lineage(path, expected_bytes, updated):
    """Orchestrator-only CAS under a short exclusive lock. Stale writers fail closed."""
    path = Path(path)
    require(not path.is_symlink(), 'symlink-forbidden')
    lock = path.with_name(path.name + '.master-cache.lock')
    try:
        fd = os.open(lock, os.O_CREAT | os.O_EXCL | os.O_WRONLY, 0o600)
    except FileExistsError:
        raise CacheError('lineage-locked') from None
    try:
        os.close(fd)
        require(path.read_bytes() == expected_bytes, 'lineage-changed')
        atomic_file(path, (json.dumps(updated, ensure_ascii=False, indent=2) + '\n').encode(), replace=True)
    finally:
        lock.unlink()


def load_backend(config_path, repo):
    if not config_path:
        return None
    config_path = private_path(config_path, repo)
    config = json.loads(config_path.read_text())
    if config['backend'] == 'directory-test':
        return DirectoryBackend(config['root'], repo)
    require(config['backend'] == 'command', 'unknown-backend')
    return CommandBackend(config['command'], config['backendId'])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('operation', choices=['probe', 'persist', 'lookup', 'restore'])
    parser.add_argument('--repo', default=str(Path(__file__).resolve().parent.parent))
    parser.add_argument('--config', default=os.environ.get('IMAGE_MASTER_CACHE_CONFIG'))
    parser.add_argument('--revision')
    parser.add_argument('--input')
    parser.add_argument('--attestation')
    parser.add_argument('--recipe-key')
    parser.add_argument('--output')
    args = parser.parse_args()
    try:
        repo = Path(args.repo).resolve()
        backend = load_backend(args.config, repo)
        if args.operation == 'probe':
            if backend is None:
                result = miss('backend-unconfigured')
            else:
                info = capabilities(backend)
                # Do not echo arbitrary provider fields, paths or diagnostics.
                result = {key: info.get(key) for key in ['backendId', 'private', 'durable', 'read', 'write', 'immutable', 'retention']}
                result['state'] = 'backend-probed'
            print(json.dumps(result))
            return 0
        path = repo / 'shared/images/image-lineage.json'
        baseline = path.read_bytes()
        lineage = json.loads(baseline)
        if args.operation == 'lookup':
            result = lookup(lineage, args.recipe_key or '', backend, args.revision)
        elif args.operation == 'restore':
            require(bool(args.revision and args.output), 'revision-and-output-required')
            result = restore(lineage, args.revision, backend, args.output, repo)
        else:
            require(backend is not None, 'backend-unconfigured')
            require(bool(args.revision and args.input and args.attestation), 'persist-arguments-required')
            data = read_bytes(private_path(args.input, repo))
            attestation = json.loads(private_path(args.attestation, repo).read_text())
            updated, result = persist(lineage, args.revision, data, attestation, backend)
            if updated is not None:
                commit_lineage(path, baseline, updated)
        print(json.dumps(result))
        return 0 if result.get('reusable') else 2
    except Exception as error:
        print(json.dumps(miss(failure(error))))
        return 2


if __name__ == '__main__':
    raise SystemExit(main())
